void draw_string(SDL_Renderer* ren, int x, int y, const char* text, u8 r, u8 g, u8 b, int scale) {
    SDL_SetRenderDrawColor(ren, r, g, b, 255);
    int cx = x;
    for (const char* p = text; *p; ++p) {
        if (*p == '\n') { y += 8 * scale + 2; cx = x; continue; }
        int idx = 0;
        unsigned char c = static_cast<unsigned char>(*p);
        if (c >= 32 && c <= 126) idx = c - 32;
        for (int row = 0; row < 7; row++) {
            u8 bits = FONT[idx][row];
            for (int col = 0; col < 4; col++) {
                if (bits & (8 >> col)) {
                    SDL_Rect px{cx + col * scale, y + row * scale, scale, scale};
                    SDL_RenderFillRect(ren, &px);
                }
            }
        }
        cx += 5 * scale + (scale > 1 ? 1 : 0);
    }
}

